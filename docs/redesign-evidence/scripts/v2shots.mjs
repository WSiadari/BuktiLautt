// node v2shots.mjs <out> [widths]
import { chromium } from "playwright-core";
import fs from "node:fs";
const [out, widthsArg = "390,1440"] = process.argv.slice(2);
fs.mkdirSync(out, { recursive: true });
const base = "http://127.0.0.1:5173";
const b = await chromium.launch({ channel: "chrome", headless: true });
const report = [];
for (const w of widthsArg.split(",").map(Number)) {
  const h = w < 500 ? 844 : w < 1000 ? 1024 : 900;
  const ctx = await b.newContext({ viewport: { width: w, height: h } });
  const p = await ctx.newPage();
  const errs = [];
  p.on("pageerror", (e) => errs.push(e.message));
  const full = async (name) => {
    const t = await p.addStyleTag({ content: ".action-bar,.site-header{position:static!important}.chat-launcher{display:none!important}" });
    await p.screenshot({ path: `${out}/${w}-${name}-full.png`, fullPage: true });
    await t.evaluate((n) => n.remove());
  };
  const fold = (name) => p.screenshot({ path: `${out}/${w}-${name}.png` });
  const ov = async (name) => {
    const o = await p.evaluate(() => document.documentElement.scrollWidth > innerWidth);
    if (o) report.push(`${w} ${name}: overflow-x`);
  };
  // loading screen (sesi akun ditahan 2,5 detik)
  await p.route("**/api/account/session", async (r) => { await new Promise((s) => setTimeout(s, 2500)); await r.continue(); });
  await p.goto(base + "/dashboard");
  await p.waitForTimeout(900);
  await fold("loading");
  await p.unroute("**/api/account/session");
  await p.goto(base + "/", { waitUntil: "networkidle" });
  await p.waitForTimeout(900);
  await fold("home");
  await full("home");
  await ov("home");
  await p.getByRole("button", { name: /^Buka contoh/ }).first().click();
  await p.waitForTimeout(900);
  await fold("timbang");
  await full("timbang");
  await ov("timbang");
  await p.getByRole("button", { name: /Konfirmasi catatan timbang/ }).click();
  await p.waitForTimeout(900);
  await p.evaluate(() => scrollTo(0, 0));
  await fold("nota");
  await full("nota");
  await ov("nota");
  report.push(`${w} nota scrollHeight ${await p.evaluate(() => document.documentElement.scrollHeight)}`);
  await p.locator('input[placeholder="Belum diketahui"][inputmode="decimal"]').first().fill("10");
  await p.getByRole("button", { name: /Konfirmasi nota/ }).click();
  await p.waitForTimeout(900);
  await p.evaluate(() => scrollTo(0, 0));
  await fold("pasangan");
  await full("pasangan");
  await ov("pasangan");
  await p.getByRole("button", { name: /Konfirmasi pasangan Teri/ }).click();
  await p.waitForTimeout(300);
  await p.getByRole("button", { name: /Konfirmasi pasangan Tongkol/ }).click();
  await p.waitForTimeout(500);
  await full("pasangan-ok");
  await p.getByRole("button", { name: /Lihat laporan/ }).click();
  await p.waitForTimeout(900);
  await p.evaluate(() => scrollTo(0, 0));
  await fold("laporan");
  await ov("laporan");
  await p.locator(".chat-launcher").click();
  await p.waitForTimeout(800);
  await fold("chat");
  await p.keyboard.press("Escape");
  await p.waitForTimeout(400);
  await p.goto(base + "/masuk", { waitUntil: "networkidle" });
  await p.waitForTimeout(900);
  await fold("masuk");
  await ov("masuk");
  await p.goto(base + "/daftar", { waitUntil: "networkidle" });
  await p.waitForTimeout(900);
  await fold("daftar");
  report.push(`${w} errors ${JSON.stringify(errs)}`);
  await ctx.close();
}
console.log(report.join("\n"));
await b.close();
