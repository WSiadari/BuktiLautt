// Fitur wajib v2: ganti akun, mode scan Foto/Teks/Suara, tombol AI, arsip, chat.
import { chromium } from "playwright-core";
const [out, base = "http://127.0.0.1:4173"] = process.argv.slice(2);
const b = await chromium.launch({ channel: "chrome", headless: true });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 } });
const p = await ctx.newPage();
const errs = [];
p.on("pageerror", (e) => errs.push(e.message));
p.on("dialog", (d) => d.accept());
const log = (...a) => console.log(...a);
// 1. mode sumber
await p.goto(base + "/", { waitUntil: "networkidle" });
await p.getByRole("button", { name: /^Mulai periksa/ }).click();
await p.waitForTimeout(600);
const modes = await p.locator(".source-panel .segmented button").allInnerTexts();
log("[scan] mode sumber timbang:", JSON.stringify(modes.map((s) => s.trim())));
await p.locator(".source-panel .segmented button", { hasText: "Foto" }).click();
log("[scan] input foto ada:", await p.locator(".source-panel input[type=file]").count());
await p.screenshot({ path: `${out}/fitur-scan-timbang-390.png` });
await p.locator(".source-panel .segmented button", { hasText: "Suara" }).click();
await p.waitForTimeout(400);
log("[scan] panel suara tampil:", (await p.locator(".source-panel .voice-input, .source-panel [class*=voice]").count()) > 0);
await p.screenshot({ path: `${out}/fitur-suara-390.png` });
await p.locator(".source-panel .segmented button", { hasText: "Teks" }).click();
await p.locator(".source-panel textarea").fill("Teri 12 kg");
log("[scan] tombol AI:", (await p.locator(".source-panel .button.ai").innerText()).trim(), "| aktif:", await p.locator(".source-panel .button.ai").isEnabled());
await p.locator(".source-panel .button.ai").click();
await p.waitForTimeout(400);
log("[scan] dialog persetujuan AI:", await p.locator("dialog[open] h2").innerText().catch(() => "-"));
await p.screenshot({ path: `${out}/fitur-persetujuan-ai-390.png` });
await p.keyboard.press("Escape");
await p.waitForTimeout(400);
// 2. ganti akun: daftar akun baru -> keluar -> masuk akun demo
const email = `uji${Date.now()}@buktilaut.test`;
await p.goto(base + "/daftar", { waitUntil: "networkidle" });
await p.locator("input[name=name]").fill("Uji Ganti Akun");
await p.locator("input[type=email]").fill(email);
await p.locator("input[type=password]").fill("Sintetis-Uji-1234");
await p.locator("form button[type=submit]").click();
await p.waitForURL(/dashboard/, { timeout: 15000 });
await p.waitForTimeout(800);
log("[akun] daftar berhasil, judul:", await p.locator("h1").first().innerText());
await p.locator(".dashboard-account summary").click();
await p.getByRole("button", { name: /Keluar dari akun/ }).click();
await p.waitForTimeout(1200);
log("[akun] setelah keluar URL:", p.url());
await p.goto(base + "/masuk", { waitUntil: "networkidle" });
await p.locator("input[type=email]").fill("demo@buktilaut.test");
await p.locator("input[type=password]").fill("Demo-Sintetis-48!");
await p.locator("form button[type=submit]").click();
await p.waitForURL(/dashboard/, { timeout: 15000 });
await p.waitForTimeout(800);
log("[akun] masuk akun lain, judul:", await p.locator("h1").first().innerText());
await p.screenshot({ path: `${out}/fitur-dashboard-ganti-akun-390.png` });
// 3. arsip
await p.getByRole("button", { name: /Buka arsip transaksi/ }).click();
await p.waitForTimeout(1000);
log("[arsip] entri:", await p.locator(".archive-entry").count());
await p.screenshot({ path: `${out}/fitur-arsip-390.png`, fullPage: true });
log("[errors]", JSON.stringify(errs));
await b.close();
